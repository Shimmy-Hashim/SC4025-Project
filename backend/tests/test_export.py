import copy
import json
from datetime import date
from pathlib import Path

import pytest

from trust_score.export import (
    build_document,
    factor_to_dict,
    is_number,
    offer_to_dict,
    validate,
    validate_seller,
    validate_weights,
    weights_to_list,
)
from trust_score.models import FactorResult, FlaggedReview, SellerRecord
from trust_score.scoring import ScoredOffer

REPO = Path(__file__).resolve().parent.parent.parent
KEYS = ["history", "brand", "price", "reviews", "complaints"]


def _offer(band="High", score=90, reason=None):
    factors = {k: FactorResult("pass", "s", "t", "src") for k in KEYS}
    factors["reviews"].flagged = [FlaggedReview("Authenticity", 1, "fake")]
    factors["reviews"].excluded_duplicates = 2
    seller = SellerRecord("A", "Seller A", 254900, "Tomorrow", 400)
    return ScoredOffer(seller, band, score, reason, ["price", "history", "brand"], factors)


def _valid_doc():
    return build_document({"title": "T", "shortTitle": "t"}, [_offer()], date(2026, 11, 6))


def test_factor_to_dict_plain_factor_has_four_fields():
    assert factor_to_dict(FactorResult("pass", "s", "t", "src")) == {
        "status": "pass", "short": "s", "text": "t", "source": "src"}


def test_factor_to_dict_includes_severity_when_set():
    assert factor_to_dict(FactorResult("warn", "s", "t", "src", severity="alert"))["severity"] == "alert"


def test_validate_rejects_bad_alert_and_severity():
    doc = _valid_doc()
    doc["sellers"][0]["alert"] = 5
    doc["sellers"][0]["factors"]["price"]["severity"] = "alert"
    assert validate(doc) == ["sellers[0].alert must be text or null.",
                             "sellers[0].factors.price.severity must be concern or alert, on a warn status only."]


def test_factor_to_dict_reviews_adds_flagged_and_duplicates():
    out = factor_to_dict(_offer().factors["reviews"])
    assert out["flagged"] == [{"tag": "Authenticity", "stars": 1, "text": "fake"}]
    assert out["excludedDuplicates"] == 2


def test_offer_to_dict_shape():
    out = offer_to_dict(_offer())
    assert list(out) == ["id", "name", "price", "delivery", "band", "score", "reason", "alert", "inline", "factors"]
    assert list(out["factors"]) == KEYS
    assert (out["id"], out["price"], out["score"]) == ("A", 254900, 90)


def test_build_document_sets_updated_and_note():
    doc = _valid_doc()
    assert doc["updated"] == "2026-11-06"
    assert doc["_note"].startswith("Generated by backend/trust_score")


def test_validate_accepts_generated_document():
    assert validate(_valid_doc()) == []


def test_validate_accepts_original_hand_written_demo():
    original = Path(__file__).resolve().parent / "fixtures/handwritten_demo_data.json"
    assert validate(json.loads(original.read_text(encoding="utf-8"))) == []


def test_validate_rejects_non_object():
    assert validate([1, 2]) == ["File is not a JSON object."]


def test_validate_reports_missing_product_and_sellers():
    assert validate({}) == ["product.title is missing.", "product.shortTitle is missing.",
                            "sellers must be a non-empty list."]


@pytest.mark.parametrize("change, message", [
    ({"id": ""}, "sellers[0].id is missing."),
    ({"price": "254900"}, "sellers[0].price must be a number in rupees."),
    ({"band": "Great"}, "sellers[0].band must be High, Medium, Low or Not enough data."),
    ({"score": None}, "sellers[0].score must be a number, or null when band is Not enough data."),
    ({"band": "Not enough data", "score": None, "reason": None},
     "sellers[0].reason is required when band is Not enough data."),
    ({"inline": ["price"]}, "sellers[0].inline must list exactly 3 factor keys."),
    ({"inline": ["price", "history", "colour"]}, 'sellers[0].inline has unknown key "colour".'),
])
def test_validate_seller_messages_match_app_js(change, message):
    doc = _valid_doc()
    doc["sellers"][0].update(change)
    assert validate(doc) == [message]


def test_validate_factor_status_and_fields():
    doc = _valid_doc()
    doc["sellers"][0]["factors"]["brand"] = {"status": "ok"}
    assert validate(doc) == ["sellers[0].factors.brand.status must be pass, warn or na.",
                             "sellers[0].factors.brand needs short, text and source."]


def test_validate_seller_missing_factors_object():
    seller = copy.deepcopy(_valid_doc()["sellers"][0])
    del seller["factors"]
    assert len(validate_seller(seller, "s")) == 10


@pytest.mark.parametrize("value, expected", [(1, True), (1.5, True), (True, False), ("1", False),
                                             (None, False)])
def test_is_number_matches_javascript_typeof(value, expected):
    assert is_number(value) is expected


def test_weights_to_list_highest_first_with_reasons():
    weights = weights_to_list()
    assert [(w["factor"], w["weight"]) for w in weights] == [
        ("reviews", 29), ("complaints", 26), ("price", 17), ("brand", 16), ("history", 12)]
    assert all(w["why"] for w in weights)


def test_build_document_includes_weights():
    assert _valid_doc()["weights"] == weights_to_list()


def test_validate_weights_optional_and_checked():
    assert validate_weights(None) == []
    assert validate_weights(weights_to_list()) == []
    assert validate_weights([{"factor": "reviews", "weight": 100, "why": "x"}]) == [
        "weights must list each factor once with a number weight and a why text."]
    wrong_total = [dict(w, weight=10) for w in weights_to_list()]
    assert validate_weights(wrong_total) == ["weights must total 100."]
