"""Build the data.json document the frontend reads, and check it the way app.js does."""

from datetime import date
from typing import Any, Dict, List

from trust_score import constants as c
from trust_score.config import (
    BAND_HIGH,
    BAND_LOW,
    BAND_MEDIUM,
    BAND_NOT_ENOUGH_DATA,
    FACTOR_ORDER,
    FACTOR_WEIGHTS,
)
from trust_score.models import FactorResult
from trust_score.scoring import ScoredOffer

NOTE = ("Generated by backend/trust_score from synthetic seller data. Sellers, ratings, reviews "
        "and scores are fictional. Regenerate with: python -m trust_score.cli build")
BANDS = (BAND_HIGH, BAND_MEDIUM, BAND_LOW, BAND_NOT_ENOUGH_DATA)
STATUSES = ("pass", "warn", "na")
SEVERITIES = ("concern", "alert")


def factor_to_dict(factor: FactorResult) -> Dict[str, Any]:
    """One factor in the frontend's shape; reviews also carry flagged and excludedDuplicates."""
    out: Dict[str, Any] = {"status": factor.status, "short": factor.short, "text": factor.text,
                           "source": factor.source}
    if factor.severity is not None:
        out["severity"] = factor.severity
    if factor.flagged is not None:
        out["flagged"] = [{"tag": f.tag, "stars": f.stars, "text": f.text} for f in factor.flagged]
        out["excludedDuplicates"] = factor.excluded_duplicates or 0
    return out


def offer_to_dict(offer: ScoredOffer) -> Dict[str, Any]:
    """One seller entry in the frontend's shape."""
    return {
        "id": offer.seller.seller_id,
        "name": offer.seller.name,
        "price": offer.seller.price,
        "delivery": offer.seller.delivery,
        "band": offer.band,
        "score": offer.score,
        "reason": offer.reason,
        "alert": offer.alert,
        "inline": offer.inline,
        "factors": {k: factor_to_dict(offer.factors[k]) for k in FACTOR_ORDER},
    }


def weights_to_list() -> List[Dict[str, Any]]:
    """Factor weights with their shopper-facing reasons, highest weight first."""
    ordered = sorted(FACTOR_ORDER, key=lambda k: -FACTOR_WEIGHTS[k])
    return [{"factor": k, "weight": FACTOR_WEIGHTS[k], "why": c.WEIGHT_REASONS[k]} for k in ordered]


def build_document(product: Dict[str, Any], offers: List[ScoredOffer], updated: date) -> Dict[str, Any]:
    """The full data.json document."""
    return {"_note": NOTE, "updated": updated.isoformat(), "product": product,
            "weights": weights_to_list(), "sellers": [offer_to_dict(o) for o in offers]}


def validate(doc: Any) -> List[str]:
    """Problems with a data.json document, mirroring validate() in app.js. Empty means valid."""
    if not isinstance(doc, dict):
        return ["File is not a JSON object."]
    errs = []
    product = doc.get("product")
    if not (isinstance(product, dict) and isinstance(product.get("title"), str)):
        errs.append("product.title is missing.")
    if not (isinstance(product, dict) and isinstance(product.get("shortTitle"), str)):
        errs.append("product.shortTitle is missing.")
    errs.extend(validate_weights(doc.get("weights")))
    sellers = doc.get("sellers")
    if not (isinstance(sellers, list) and sellers):
        errs.append("sellers must be a non-empty list.")
    for i, s in enumerate(sellers if isinstance(sellers, list) else []):
        errs.extend(validate_seller(s, f"sellers[{i}]"))
    return errs


def validate_weights(weights: Any) -> List[str]:
    """Problems with the optional weights list: each factor once, numbers totalling 100."""
    if weights is None:
        return []
    ok = (isinstance(weights, list) and all(isinstance(w, dict) and w.get("factor") in FACTOR_ORDER
                                            and is_number(w.get("weight")) and isinstance(w.get("why"), str)
                                            for w in weights))
    if not ok or sorted(w["factor"] for w in weights) != sorted(FACTOR_ORDER):
        return ["weights must list each factor once with a number weight and a why text."]
    if sum(w["weight"] for w in weights) != 100:
        return ["weights must total 100."]
    return []


def validate_seller(s: Dict[str, Any], at: str) -> List[str]:
    """Problems with one seller entry, mirroring app.js."""
    errs = []
    if not s.get("id"):
        errs.append(at + ".id is missing.")
    if not is_number(s.get("price")):
        errs.append(at + ".price must be a number in rupees.")
    band = s.get("band")
    if band not in BANDS:
        errs.append(at + ".band must be High, Medium, Low or Not enough data.")
    score_ok = s.get("score") is None if band == BAND_NOT_ENOUGH_DATA else is_number(s.get("score"))
    if not score_ok:
        errs.append(at + ".score must be a number, or null when band is Not enough data.")
    if band == BAND_NOT_ENOUGH_DATA and not isinstance(s.get("reason"), str):
        errs.append(at + ".reason is required when band is Not enough data.")
    if s.get("alert") is not None and not isinstance(s.get("alert"), str):
        errs.append(at + ".alert must be text or null.")
    inline = s.get("inline")
    if not (isinstance(inline, list) and len(inline) == 3):
        errs.append(at + ".inline must list exactly 3 factor keys.")
    factors = s.get("factors") if isinstance(s.get("factors"), dict) else {}
    for k in FACTOR_ORDER:
        f = factors.get(k)
        if not (isinstance(f, dict) and f.get("status") in STATUSES):
            errs.append(f"{at}.factors.{k}.status must be pass, warn or na.")
        if not (isinstance(f, dict) and f.get("short") and f.get("text") and f.get("source")):
            errs.append(f"{at}.factors.{k} needs short, text and source.")
        if isinstance(f, dict) and "severity" in f and not (f.get("status") == "warn" and f["severity"] in SEVERITIES):
            errs.append(f"{at}.factors.{k}.severity must be concern or alert, on a warn status only.")
    for k in inline if isinstance(inline, list) else []:
        if k not in FACTOR_ORDER:
            errs.append(f'{at}.inline has unknown key "{k}".')
    return errs


def is_number(value: Any) -> bool:
    """JSON number check matching JavaScript's typeof === "number" (bools excluded)."""
    return isinstance(value, (int, float)) and not isinstance(value, bool)
